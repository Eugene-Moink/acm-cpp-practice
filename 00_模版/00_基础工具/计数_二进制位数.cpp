/* =====================================================
二进制位数

【用途】
  求非负整数 n 的二进制表示有多少位（最高位 1 的下标 + 1）。
【输入】
  n (ll)，非负整数。
【输出】
  int，位数；bit_length(0) 约定为 0。
【复杂度】
  O(log n)。
【易错提醒】
  1. 参数必须用 ll，用 int 会在 32 位处溢出。
  2. n == 0 返回 0；若题目要求「0 也算 1 位」需自行特判。
  3. 想要的是最高位下标时别忘了减 1（下标 = bit_length(n) - 1）。
  4. 另一种写法：`64 - __builtin_clzll(n)`（n == 0 时未定义）。
===================================================== */
int bit_length(ll n)
{
    int len = 0;
    while (n > 0)
    {
        len++;
        n >>= 1;
    }
    return len;
}