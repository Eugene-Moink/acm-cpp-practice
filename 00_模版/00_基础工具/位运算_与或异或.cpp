/* =====================================================
按位与 / 或 / 异或

【用途】
  读入 a, b 并输出 a|b、a&b、a^b 三个值，作为位运算题的起手式。
【输入】
  a, b (ll)。
【输出】
  一行三个数：按位或、按位与、按位异或。
【复杂度】
  O(1)。
【易错提醒】
  1. 异或的优先级低于比较运算符，`a ^ b == c` 会先算 `==`，必须加括号。
  2. 多组数据在 main 里循环调用 solve()。
  3. 负数右移是实现定义行为，不要依赖算术右移还是逻辑右移。
===================================================== */
void solve()
{
    ll a, b;
    cin >> a >> b;
    cout << (a | b) << ' ' << (a & b) << ' ' << (a ^ b) << '\n';
}

/* ==================== 调用示例（贴进自己的 main） ====================
    int t;
    cin >> t;
    while (t--)
        solve();
==================================================================== */