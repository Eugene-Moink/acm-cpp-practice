/* =====================================================
按位与 / 或 / 异或

【用途】
  读入 a, b，输出 a|b、a&b、a^b 三个值。多组数据请在 main 里循环调用 solve()。
===================================================== */
void solve()
{
    ll a, b;
    cin >> a >> b;
    cout << (a | b) << ' ' << (a & b) << ' ' << (a ^ b) << '\n';
}

