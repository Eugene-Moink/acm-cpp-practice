/* =====================================================
二进制位运算（GCC 内置函数）

【用途】
  处理二进制表示相关的高效查询：1 的个数、最低位 1 的下标、最高位 1 的下标。
【输入】
  x (ll)，非负整数。
【输出】
  一行三个数：1 的个数、最低位 1 的下标、最高位 1 的下标；x == 0 时输出 "0 -1 -1"。
【复杂度】
  O(1)。
【易错提醒】
  1. 必须用 long long 且函数后缀写 ll，否则会算错。
  2. x == 0 时 __builtin_ctzll / __builtin_clzll 行为未定义，必须特判。
  3. 要「最低位 1 的值」用 x & -x，要「下标」才用 __builtin_ctzll。
  4. 最高位下标 = 63 - __builtin_clzll(x)。
===================================================== */

void solve()
{
    ll x;
    cin >> x;

    if (x == 0)
    {
        cout << "0 -1 -1" << '\n';
        return;
    }

    ll one = __builtin_popcountll(x);

    ll min_one = __builtin_ctzll(x);

    ll max_one = 63 - __builtin_clzll(x);

    cout << one << " " << min_one << " " << max_one << '\n';
}

/* ==================== 调用示例（贴进自己的 main） ====================
    cin >> x;                       // 例如 x = 0b101100
    solve();                        // 输出：1 的个数 / 最低位 1 / 最高位 1
    // x == 0 时输出 "0 -1 -1"
==================================================================== */