/* =====================================================
整数划分计数

【用途】
  整数划分（把 n 写成若干个正整数之和，不计顺序）的两类计数：
  ① 恰好 k 个部分：dp[i][j] = dp[i-1][j-1] + dp[i-j][j]；
  ② 任意个部分：完全背包式 dp[j] += dp[j-i]（物品是 1..n 的每个整数，可无限次使用）。
  典型题：洛谷 P102 数的划分。
【输入】
  partition_into_k：n（被划分数）、k（部分数）。
  partition_number：n。
【输出】
  方案数（ll；n 较大时会溢出，按题目要求取模）。
【复杂度】
  ① O(n·k) 时间、O(n·k) 空间（可压成一维逆序）；② O(n²) 时间、O(n) 空间。
【易错提醒】
  1. 划分「不计顺序」，所以不能用组合数 C(n-1, k-1)（那是「正整数解个数」，把顺序也算进去了）。
  2. ①的转移含义：含 1 的划分（去掉一个 1 → dp[i-1][j-1]）与不含 1 的划分（每部分减 1 → dp[i-j][j]）。
  3. ②必须外层枚举部分大小 i、内层容量正序（完全背包），反过来会算成有序拆分。
  4. 初值：① dp[0][0] = 1，其余 0；② dp[0] = 1。
  5. 溢出：n = 100 时 p(n) ≈ 1.9×10^8，n = 400 时已超 ll；需要取模就全程取模。
  6. n < k 时答案为 0；k = 0 且 n > 0 时答案为 0。
===================================================== */
ll partition_into_k(int n, int k, ll mod)
{
    if (n < k || k < 0)
    {
        return 0;
    }

    vector<vector<ll>> dp(n + 1, vector<ll>(k + 1, 0));
    dp[0][0] = 1;

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= k && j <= i; j++)
        {
            ll v = dp[i - 1][j - 1];                      // 至少有一个 1
            if (i >= j)
            {
                v += dp[i - j][j];                         // 每个部分都 >= 2
            }
            dp[i][j] = (mod > 0 ? v % mod : v);
        }
    }
    return dp[n][k];
}

ll partition_number(int n, ll mod)
{
    vector<ll> dp(n + 1, 0);
    dp[0] = 1;
    for (int i = 1; i <= n; i++)
    {
        for (int j = i; j <= n; j++)
        {
            dp[j] += dp[j - i];
            if (mod > 0)
            {
                dp[j] %= mod;
            }
        }
    }
    return dp[n];
}

