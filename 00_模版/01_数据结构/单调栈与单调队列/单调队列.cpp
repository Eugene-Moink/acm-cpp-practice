/*
 * 【用途】单调队列（滑动窗口模板）：定长窗口内的最大值、最小值。
 * 【输入】数组 a（vector<int>，0-based，允许为空）与窗口长度 k。
 * 【输出】vector<int>，长度为 n - k + 1，第 i 位是 a[i .. i + k - 1] 的最大 / 最小值；
 *         k <= 0 或 k > n 时没有合法窗口，返回空数组。
 * 【复杂度】O(n) 时间、O(k) 空间（每个下标最多进队一次、出队一次）。
 * 【易错提醒】1) 队列里存下标而不是值，否则无法判断队首是否滑出窗口；
 *             2) 每轮的顺序固定为「先弹队尾维持单调、再压入当前下标、再弹队首去过期」；
 *             3) 求最小值只需把队尾的比较符号反过来（见分节二）；
 *             4) 必须特判 k <= 0 与 k > n，否则长度计算和 front() 都会出错；
 *             5) 元素值可能超过 2^31 时，把数组与返回值的元素类型整体换成 ll。
 */

/* ==================== 一、定长窗口最大值 ====================
 * 队内下标对应的值单调递减，队首就是当前窗口最大值；
 * 弹队尾时用 <=（而不是 <），让相等的旧值出队，保留更晚出现的那个，避免它提前过期。
 * ======================================================== */
vector<int> window_max(const vector<int> &a, int k)
{
    int n = (int)a.size();
    vector<int> res;
    if (k <= 0 || n < k)
        return res;
    res.reserve(n - k + 1);
    deque<int> dq;
    for (int i = 0; i < n; i++)
    {
        while (!dq.empty() && a[dq.back()] <= a[i])
            dq.pop_back();
        dq.push_back(i);
        while (dq.front() <= i - k)
            dq.pop_front();
        if (i >= k - 1)
            res.push_back(a[dq.front()]);
    }
    return res;
}

/* ==================== 二、定长窗口最小值 ====================
 * 与分节一完全同构，唯一差异是把弹队尾条件 a[dq.back()] <= a[i] 反过来写成 a[dq.back()] >= a[i]；
 * 此时队内下标对应的值单调递增，队首就是当前窗口最小值。
 * ======================================================== */
vector<int> window_min(const vector<int> &a, int k)
{
    int n = (int)a.size();
    vector<int> res;
    if (k <= 0 || n < k)
        return res;
    res.reserve(n - k + 1);
    deque<int> dq;
    for (int i = 0; i < n; i++)
    {
        while (!dq.empty() && a[dq.back()] >= a[i])
            dq.pop_back();
        dq.push_back(i);
        while (dq.front() <= i - k)
            dq.pop_front();
        if (i >= k - 1)
            res.push_back(a[dq.front()]);
    }
    return res;
}

/* ==================== 三、何时用单调队列而不是优先队列 ====================
 * 1. 单调队列能 O(1) 读取队首（即当前窗口极值）；优先队列虽然也能 O(1) 读堆顶，
 *    但删除过期元素要么不能删、要么惰性删除，堆里会堆积无效项，取到的极值可能是过期的。
 * 2. 单调队列适用于「窗口定长、且左右端点都只向右移动」的滑动场景：
 *    定长窗口最值、带长度限制的最优区间、DP 的滑动窗口优化。
 * 3. 若窗口不定长、需要随时按值插入删除求全局极值，或要维护动态集合的前 k 大，
 *    应改用 priority_queue（必要时配合惰性删除或对顶堆）。
 * ==================================================================== */

