/* =====================================================
最大公约数与最小公倍数

【用途】
  求两数的最大公约数与最小公倍数。
【输入】
  a, b (ll)。
【输出】
  gcd(a, b)；lcm(a, b)（任一为 0 时返回 0）。
【复杂度】
  O(log n)。
【易错提醒】
  1. lcm 必须「先除后乘」：a / gcd(a, b) * b，直接 a * b 会溢出。
  2. 有负数时先取绝对值。
  3. C++17 已有 std::gcd / std::lcm，与 using namespace std 同时使用会歧义，必要时加 std:: 或改名。
===================================================== */
ll gcd(ll a, ll b)
{
    return b == 0 ? a : gcd(b, a % b);
}

ll lcm(ll a, ll b)
{
    if (a == 0 || b == 0)
        return 0;
    return a / gcd(a, b) * b;
}