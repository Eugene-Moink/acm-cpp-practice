#include <bits/stdc++.h>
using namespace std;
using ll = long long;

void moink()
{
    int A, B;
    cin >> A >> B;
    for (int i = B; i >= 1; i--)
    {
        int cnt = B / i - (A - 1) / i;
        if (cnt >= 2)
        {
            cout << i << '\n';
            return;
        }
    }
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    moink();
    return 0;
}

